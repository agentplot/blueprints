#!/usr/bin/env python3
"""Render books/VOICE.md from styles/Blueprints: the README, then every rule
with its level, reason and what it looks for. The rules are the source;
this page is what a session reads before writing. Run by `voice`."""
import glob, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
style = os.path.join(root, "styles", "Blueprints")
out = os.path.join(root, "books", "VOICE.md")

def parse(path):
    rule = {"tokens": []}
    key = None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.startswith("  - "):
            item = line[4:].strip()
            if item.startswith("'") and item.endswith("'"):
                item = item[1:-1].replace("''", "'")
            elif item.startswith('"') and item.endswith('"'):
                item = item[1:-1]
            if key in ("tokens", "raw"):
                rule["tokens"].append(item)
            continue
        if ":" in line:
            key, _, value = line.partition(":")
            key, value = key.strip(), value.strip()
            if value.startswith('"') and value.endswith('"'):
                value = value[1:-1]
            if key == "swap":
                rule["swap"] = True
            elif value:
                rule[key] = value
    return rule

order = {"error": 0, "warning": 1, "suggestion": 2}
rules = []
for path in sorted(glob.glob(os.path.join(style, "*.yml"))):
    name = os.path.splitext(os.path.basename(path))[0]
    r = parse(path)
    r["name"] = name
    rules.append(r)
rules.sort(key=lambda r: (order.get(r.get("level", "suggestion"), 3), r["name"]))

readme = open(os.path.join(style, "README.md"), encoding="utf-8").read().rstrip("\n")
lines = ["<!-- Generated by scripts/voice.py from styles/Blueprints; edit the README and the rules there, not this page. -->", "", readme, "", "## What Vale checks", "",
         "Each rule below is a file under `styles/Blueprints`. A warning must be cleared before a commit; a suggestion is the writer's to weigh. The narration and heading rules bind chapters only.", ""]
for r in rules:
    lines.append(f"### {r['name']} ({r.get('level', 'suggestion')})")
    lines.append("")
    lines.append(r.get("description", "").strip())
    lines.append("")
    msg = r.get("message", "").replace("%s", "…")
    lines.append(f"Message: {msg}")
    lines.append("")
    if r["tokens"]:
        shown = [t for t in r["tokens"] if not re.search(r"[\\()\[\]|?*+^$]", t)]
        if shown:
            lines.append("Looks for: " + ", ".join(shown) + ".")
        else:
            lines.append("Looks for: a pattern; see the rule.")
        lines.append("")
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines).rstrip("\n") + "\n")
print(f"voice: {len(rules)} rules rendered into books/VOICE.md")
